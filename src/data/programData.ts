export const PROGRAM_WEEKS: WeekPlan[] = Array.from({ length: 12 }, (_, i) => {
  const weekNum = i + 1;
  const blockNum = weekNum <= 4 ? 1 : weekNum <= 8 ? 2 : 3;
  const isDeload = weekNum === 5 || weekNum === 12; // Deload / recovery bridge

  let dayAExercises = block1DayAExercises;
  let dayBExercises = block1DayBExercises;
  let blockTitle = 'Phase 1: Hypertrophic Foundation';

  if (blockNum === 2) {
    dayAExercises = block2DayAExercises;
    dayBExercises = block2DayBExercises;
    blockTitle = 'Phase 2: Novelty & Overload Progression';
  } else if (blockNum === 3) {
    dayAExercises = block3DayAExercises;
    dayBExercises = block3DayBExercises;
    blockTitle = 'Phase 3: Peak Intensity & Density Specialization';
  }

  const dayATemplate: DayWorkoutTemplate = {
    id: `w${weekNum}-dayA`,
    dayType: 'Full Body A',
    title: `Week ${weekNum} - Full Body A`,
    description: 'High-intensity compound chest, hinge, vertical pull & arms/delts overload.',
    exercises: dayAExercises,
  };

  const dayBTemplate: DayWorkoutTemplate = {
    id: `w${weekNum}-dayB`,
    dayType: 'Full Body B',
    title: `Week ${weekNum} - Full Body B`,
    description: 'Squat pattern, horizontal pull, incline press, knee flexion & core density.',
    exercises: dayBExercises,
  };

  return {
    weekNumber: weekNum,
    blockNumber: blockNum,
    blockTitle,
    isDeload,
    notes: isDeload
      ? 'Deload/Recovery focus: Target 1-2 RIR in the tank. Lower joint stress while retaining muscle memory and preparing for progression.'
      : `Week ${weekNum} of the 12-week scientific cycle. Focus on beating last week's logbook by 1 rep or +1-2.5 kg.`,
    workouts: {
      dayA: dayATemplate,
      dayB: dayBTemplate,
    },
  };
});

